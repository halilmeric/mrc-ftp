let lang = 'tr';
// İşlev bildirimi olmaları bilinçli: format.js node'da aynı adları `var` ile alır, tarayıcıda çakışmamalı.
function setLang(next) { lang = next === 'en' ? 'en' : 'tr'; }
function getLang() { return lang; }

// t('metin') ya da t`metin ${deger}`. İngilizce karşılıkta {} sırayla, {0} {1} ise numarayla dolar.
function t(text, ...values) {
  const parts = Array.isArray(text) ? text : [text];
  const key = parts.join('{}');
  const found = lang === 'en' ? EN[key] : undefined;
  if (found === undefined) return parts.reduce((out, part, i) => out + values[i - 1] + part);
  let next = 0;
  return found.replace(/\{(\d*)\}/g, (_, n) => values[n === '' ? next++ : Number(n)]);
}

// Sayfadaki sabit metinleri (HTML'de yazılı olanları) bir kez çevirir. Dosya adı gibi veriler bu sırada sayfada yoktur.
function localize(root) {
  root.ownerDocument.documentElement.lang = lang;
  if (lang === 'tr') return;
  const walker = root.ownerDocument.createTreeWalker(root, 4); // metin düğümleri
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    const text = node.nodeValue.trim();
    if (text && EN[text] !== undefined) node.nodeValue = node.nodeValue.replace(text, EN[text]);
  }
  for (const el of root.querySelectorAll('[title], [placeholder], [aria-label]')) {
    for (const attr of ['title', 'placeholder', 'aria-label']) {
      const value = el.getAttribute(attr);
      if (value && EN[value] !== undefined) el.setAttribute(attr, EN[value]);
    }
  }
}

if (typeof module !== 'undefined') module.exports = { t, setLang, getLang, localize, EN };
